"""Accès à la base : SQLite sur un PC, PostgreSQL en ligne.

Le reste du code écrit ses requêtes une seule fois, en SQL commun avec des `?`.
Cette couche :
  - traduit `?` en `%s` et `IS NOT ?` en `IS DISTINCT FROM %s` pour PostgreSQL ;
  - renvoie des lignes lisibles par nom (`row["email"]`) ET par position (`row[0]`) ;
  - fournit `insert()` qui renvoie l'identifiant créé sur les deux bases ;
  - expose `IntegrityError` (doublon d'e-mail…) quel que soit le moteur.

Choix : SQLite (aucune installation) quand DATABASE_URL est vide ; PostgreSQL
(ex. Neon gratuit) dès que DATABASE_URL est défini, car le disque des hébergeurs
gratuits est effacé à chaque redémarrage.
"""
from __future__ import annotations

